from __future__ import annotations

import ssl
import time
from dataclasses import dataclass

import httpx


def _create_ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context()
    try:
        ctx.load_default_certs()
    except Exception:
        pass
    return ctx

# Cloudflare's speed-test endpoint returns exactly the requested number of
# generated bytes, no auth, and is meant for exactly this purpose - no need
# to host our own test file or depend on a specific static file staying put
# on someone else's server.
_TEST_URL = "https://speed.cloudflare.com/__down"
_DEFAULT_SIZE_BYTES = 10_000_000  # 10 MB
_TIMEOUT_SECONDS = 15.0
_CHUNK_SIZE = 65536


@dataclass
class SpeedtestResult:
    download_mbps: float
    bytes_downloaded: int
    elapsed_seconds: float
    server: str


async def _download(
    size_bytes: int, timeout: float, *, transport: httpx.AsyncBaseTransport | None = None
) -> SpeedtestResult:
    """Streams the test payload and discards it chunk by chunk (nothing is
    buffered). ``timeout`` is httpx's per-operation timeout (connect, and
    each read), the same semantics the previous ``requests`` call had.
    ``transport`` exists so tests can serve a canned response."""
    start = time.monotonic()
    downloaded = 0
    async with httpx.AsyncClient(timeout=timeout, transport=transport, verify=_create_ssl_context()) as client:
        async with client.stream("GET", _TEST_URL, params={"bytes": size_bytes}) as resp:
            resp.raise_for_status()
            async for chunk in resp.aiter_bytes(_CHUNK_SIZE):
                downloaded += len(chunk)

    elapsed = max(time.monotonic() - start, 0.001)
    mbps = (downloaded * 8 / 1_000_000) / elapsed
    return SpeedtestResult(
        download_mbps=round(mbps, 2),
        bytes_downloaded=downloaded,
        elapsed_seconds=round(elapsed, 2),
        server="speed.cloudflare.com",
    )


async def run_speedtest(size_bytes: int = _DEFAULT_SIZE_BYTES) -> SpeedtestResult:
    """Natively async (httpx), so the download never blocks - or needs a
    worker thread alongside - the event loop that runs every ping check."""
    return await _download(size_bytes, _TIMEOUT_SECONDS)
